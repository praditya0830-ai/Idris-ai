"""Build a SolidWorks VBA macro that rebuilds an IDRIS feature tree as PARAMETRIC features (P5b).

An .SLDPRT cannot be written without SolidWorks: the format is proprietary and every writer needs the licensed
API. What CAN be shipped to a buyer is a macro that opens a new part in THEIR SolidWorks and builds the same
sketch-and-feature tree, with dimensions as real dimensions, so the part is editable there and not just a frozen
solid. That is what this module writes.

Mapping (IDRIS op -> SolidWorks API):
    sketch  -> Front/Top/Right Plane + CreateCornerRectangle / CreateCircleByRadius / CreatePolygon
               + AddDimension2 with SystemValue in METRES
    extrude -> FeatureExtrusion2 (with draft if the IDRIS feature had one)
    revolve -> FeatureRevolve2 about the sketch normal
    hole    -> a circular cut through all (a Hole Wizard hole needs a standard-table selection, which a macro
               cannot make reliably, so it is a cut and the report says so)
    fillet  -> FeatureFillet3, with the edge selection left to the engineer when IDRIS selected "all"
    pattern -> FeatureLinearPattern4 / FeatureCircularPattern4

Nothing here has been run inside SolidWorks: there is no SolidWorks in this sandbox. The macro is checked for VBA
structure and for content (every feature is either a call or a stated skip), and it is reported as untested.
"""
from __future__ import annotations

import re

MM = 0.001                                  # SolidWorks API works in metres
PLANE = {"XY": "Front Plane", "XZ": "Top Plane", "YZ": "Right Plane"}
SKETCH_PLANE = {"XY": "XY", "XZ": "XZ", "YZ": "YZ"}


def _m(x):
    return f"{float(x) * MM:.6g}"


def _header(name, model):
    rev = model.get("revision")
    return [
        "Option Explicit",
        "' ============================================================================",
        f"' IDRIS -> SolidWorks: rebuild \"{name}\" as parametric features",
        f"' Model id: {model.get('model_id') or name}   revision: {rev if rev is not None else 'n/a'}",
        "' Every length below is in METRES because the SolidWorks API works in metres;",
        "' the comment on each line repeats the millimetre value IDRIS used.",
        "' Generated by IDRIS ACE from the feature graph. Not executed in SolidWorks by IDRIS:",
        "' open it in SolidWorks (Tools -> Macro -> Run) and check the rebuild before using the part.",
        "' ============================================================================",
        "Dim swApp As Object",
        "Dim swModel As Object",
        "Dim swSketchMgr As Object",
        "Dim swFeatureMgr As Object",
        "Dim swFeat As Object",
        "Dim swDim As Object",
        "Dim boolstatus As Boolean",
        "",
        "Sub main()",
        "    Set swApp = Application.SldWorks",
        "    Set swModel = swApp.NewDocument(\"\", 0, 0, 0)",
        "    If swModel Is Nothing Then",
        "        MsgBox \"Open a new part in SolidWorks first, then run this macro.\"",
        "        Exit Sub",
        "    End If",
        "    Set swSketchMgr = swModel.SketchManager",
        "    Set swFeatureMgr = swModel.FeatureManager",
        "    swSketchMgr.AddToDB = True",
        "",
    ]


def _sketch_block(fid, p, lines, report):
    plane = str(p.get("plane") or "XY").upper()
    sw_plane = PLANE.get(plane, "Front Plane")
    profile = str(p.get("profile") or "rectangle").lower()
    w = float(p.get("w") or 0.0)
    h = float(p.get("h") or w)
    n = int(p.get("n") or 6)
    off = float(p.get("offset") or 0.0)
    lines.append(f"    ' [{fid}] sketch on {plane} ({sw_plane}): {profile} {w:g} x {h:g} mm, offset {off:g} mm")
    lines.append("    swModel.ClearSelection2 True")
    lines.append(f"    boolstatus = swModel.Extension.SelectByID2(\"{sw_plane}\", \"PLANE\", 0, 0, 0, False, 0, "
                 f"Nothing, 0)")
    lines.append("    boolstatus = swSketchMgr.InsertSketch(True)")
    if profile in ("rectangle", "lshape"):
        lines.append(f"    swSketchMgr.CreateCornerRectangle({_m(-w / 2)}, {_m(-h / 2)}, 0, {_m(w / 2)}, "
                     f"{_m(h / 2)}, 0)")
        if profile == "lshape":
            t = float(p.get("thickness") or min(w, h) / 3.0)
            lines.append(f"    ' L-shape: the leg is {t:g} mm; trim the corner with a line at ({_m(t)}, 0) -> "
                         f"({_m(t)}, {_m(h / 2)}) and ({_m(t)}, {_m(t)}) -> ({_m(w / 2)}, {_m(t)})")
            report["manual"].append({"feature": fid, "what": f"the L-shape leg ({t:g} mm) needs two trim lines"})
    elif profile in ("circle", "round"):
        lines.append(f"    swSketchMgr.CreateCircleByRadius(0, 0, 0, {_m(w / 2)})")
    else:
        lines.append(f"    swSketchMgr.CreatePolygon(0, 0, 0, {_m(w / 2)}, {_m(w / 2)}, {n}, False)")
    lines.append("    boolstatus = swSketchMgr.InsertSketch(True)")
    # parametric dimensions: a rectangle is dimensioned by its width and its height
    lines.append("    ' dimensions as real SolidWorks dimensions (edit them, the part rebuilds)")
    if profile in ("rectangle", "lshape"):
        for seg, value, label in (("Line1", w, "w"), ("Line2", h, "h")):
            lines.append("    swModel.ClearSelection2 True")
            lines.append(f"    ' segment names (Line1/Line2) follow SolidWorks' own order; re-select if the "
                         f"sketch was made differently")
            lines.append(f"    boolstatus = swModel.Extension.SelectByID2(\"{seg}\", \"SKETCHSEGMENT\", 0, 0, 0, "
                         f"False, 0, Nothing, 0)")
            lines.append(f"    Set swDim = swModel.AddDimension2(0, 0.05, 0)")
            lines.append(f"    swDim.SystemValue = {_m(value)}       ' {label} = {value:g} mm")
    if abs(off) > 1e-12:
        lines.append(f"    ' the sketch was offset {off:g} mm from {sw_plane}; set that in the sketch plane "
                     f"definition if you need it exact")
        report["manual"].append({"feature": fid, "what": f"sketch offset {off:g} mm must be set on the plane"})
    report["translated"].append({"feature": fid, "op": "sketch"})
    return f"Sketch_{fid}"


def _extrude_block(fid, p, sketch_name, lines, report):
    dist = float(p.get("distance") or 0.0)
    direction = str(p.get("direction") or "+normal")
    draft = float(p.get("draft_deg") or 0.0)
    lines.append(f"    ' [{fid}] extrude {dist:g} mm, {direction}, draft {draft:g} deg")
    lines.append("    swModel.ClearSelection2 True")
    lines.append(f"    boolstatus = swModel.Extension.SelectByID2(\"{sketch_name}\", \"SKETCH\", 0, 0, 0, False, 0, "
                 f"Nothing, 0)")
    flip = ".True." if direction == "-normal" else ".False."
    both = ".True." if direction == "symmetric" else ".False."
    d = float(draft) * 0.0174532925199433           # degrees -> radians, which is what the API takes
    lines.append(f"    Set swFeat = swFeatureMgr.FeatureExtrusion2(True, False, {flip}, 0, 0, {_m(dist)}, "
                 f"{_m(dist)}, False, False, False, False, {d:.6g}, {d:.6g}, {both}, False, False, False, True, "
                 f"True, True, 0, 0, False)")
    report["translated"].append({"feature": fid, "op": "extrude"})
    return f"Boss-Extrude_{fid}"


def _revolve_block(fid, p, sketch_name, plane, lines, report):
    angle = float(p.get("angle_deg") or 360.0)
    lines.append(f"    ' [{fid}] revolve {angle:g} deg about the {str(p.get('axis') or 'z')} axis")
    lines.append("    swModel.ClearSelection2 True")
    lines.append(f"    boolstatus = swModel.Extension.SelectByID2(\"{sketch_name}\", \"SKETCH\", 0, 0, 0, False, 0, "
                 f"Nothing, 0)")
    lines.append("    ' select the centreline/axis of revolution as the second selection in SolidWorks")
    lines.append(f"    Set swFeat = swFeatureMgr.FeatureRevolve2(True, True, False, False, False, False, 0, 0, "
                 f"{angle * 0.0174532925199433:.6g}, 0, False, False, 0.01, 0.01, 0, 0, 0, 0, True, True, True)")
    report["manual"].append({"feature": fid, "what": "the axis of revolution must be selected by hand; a macro "
                                                     "cannot pick a centreline reliably"})
    report["translated"].append({"feature": fid, "op": "revolve"})
    return f"Revolve_{fid}"


def _hole_block(fid, p, plane, lines, report):
    x, y = float(p.get("x") or 0.0), float(p.get("y") or 0.0)
    d = float(p.get("d") or 0.0)
    through = bool(p.get("through", True)) or p.get("depth") is None
    depth = p.get("depth")
    sw_plane = PLANE.get(str(plane or "XY").upper(), "Front Plane")
    lines.append(f"    ' [{fid}] hole d={d:g} mm at ({x:g}, {y:g}) on {plane}"
                 + (" through all" if through else f", depth {float(depth):g} mm"))
    lines.append("    swModel.ClearSelection2 True")
    lines.append(f"    boolstatus = swModel.Extension.SelectByID2(\"{sw_plane}\", \"PLANE\", 0, 0, 0, False, 0, "
                 f"Nothing, 0)")
    lines.append("    boolstatus = swSketchMgr.InsertSketch(True)")
    lines.append(f"    swSketchMgr.CreateCircleByRadius({_m(x)}, {_m(y)}, 0, {_m(d / 2)})")
    lines.append("    boolstatus = swSketchMgr.InsertSketch(True)")
    lines.append("    swModel.ClearSelection2 True")
    lines.append(f"    boolstatus = swModel.Extension.SelectByID2(\"Sketch\", \"SKETCH\", 0, 0, 0, False, 0, "
                 f"Nothing, 0)")
    t = 1 if through else 0
    dep = 0.0 if through else float(depth) * MM
    lines.append(f"    Set swFeat = swFeatureMgr.FeatureCut4(True, False, False, {t}, 0, {dep:.6g}, {dep:.6g}, "
                 f"False, False, False, False, 0, 0, False, False, False, False, False, True, True, True, True, "
                 f"False, 0, 0, False, False)")
    report["manual"].append({"feature": fid, "what": "hole is a circular cut, not a Hole Wizard hole (no standard "
                                                     "table can be selected from a macro)"})
    report["translated"].append({"feature": fid, "op": "hole"})
    return f"Cut_{fid}"


def _fillet_block(fid, p, lines, report):
    r = float(p.get("radius") or 0.0)
    edges = str(p.get("edges") or "all")
    lines.append(f"    ' [{fid}] fillet r={r:g} mm on edges: {edges}")
    lines.append("    swModel.ClearSelection2 True")
    if edges in ("all", "ALL", ""):
        lines.append("    ' IDRIS filleted every edge; select the edges you want here (SelectAll picks faces)")
        lines.append("    boolstatus = swModel.Extension.SelectByID2(\"\", \"EDGE\", 0, 0, 0, True, 0, Nothing, 0)")
        report["manual"].append({"feature": fid, "what": "edge selection for 'all' edges is left to the engineer"})
    else:
        lines.append(f"    ' edges selector in IDRIS: {edges}")
    lines.append(f"    Set swFeat = swFeatureMgr.FeatureFillet3(195, {_m(r)}, 0, 0, 0, 0, 0, Nothing, Nothing, "
                 f"Nothing, Nothing, Nothing, Nothing)")
    report["translated"].append({"feature": fid, "op": "fillet"})
    return f"Fillet_{fid}"


def _pattern_block(fid, p, lines, report):
    mode = str(p.get("mode") or "linear").lower()
    count = int(p.get("count") or 2)
    if mode == "linear":
        dx, dy = float(p.get("dx") or 0.0), float(p.get("dy") or 0.0)
        lines.append(f"    ' [{fid}] linear pattern {count} x, step ({dx:g}, {dy:g}) mm")
        lines.append("    swModel.ClearSelection2 True")
        lines.append("    ' select the feature to pattern (the previous feature) in SolidWorks")
        lines.append(f"    Set swFeat = swFeatureMgr.FeatureLinearPattern4({count}, {_m(max(abs(dx), abs(dy)))}, "
                     f"1, 0.01, False, False, \"\", \"\", False, False, False, False, False, False, False, False, "
                     f"False, False, 0, 0, False)")
    else:
        angle = float(p.get("angle_deg") or 360.0)
        lines.append(f"    ' [{fid}] circular pattern {count} x over {angle:g} deg")
        lines.append("    swModel.ClearSelection2 True")
        lines.append("    ' select the feature and the temporary axis to pattern about")
        lines.append(f"    Set swFeat = swFeatureMgr.FeatureCircularPattern4({count}, "
                     f"{angle / max(count, 1) * 0.0174532925199433:.6g}, False, \"\", False, True, False)")
    report["manual"].append({"feature": fid, "what": "the feature to pattern must be selected in SolidWorks"})
    report["translated"].append({"feature": fid, "op": "pattern"})
    return f"Pattern_{fid}"


def _footer(lines):
    lines += ["", "    swModel.ClearSelection2 True", "    swModel.EditRebuild3", "    swModel.ViewZoomtofit2",
              "    MsgBox \"IDRIS rebuild finished. Check the feature tree and the dimensions.\"", "End Sub", ""]
    return lines


def macro_from_model(model: dict, name: str = "part") -> dict:
    """-> {"vba": text, "translated": [...], "manual": [...], "skipped": [...], "notes": [...]}."""
    model = dict(model or {})
    if "model" in model and isinstance(model["model"], dict):
        model = model["model"]
    feats = list(model.get("features") or [])
    if not feats:
        raise ValueError("the model has no feature tree, so there is nothing to rebuild: export STEP instead")
    lines = _header(name, model)
    report = {"translated": [], "manual": [], "skipped": [], "notes": []}
    last_sketch, last_plane = None, "XY"
    for f in feats:
        fid = str(f.get("id") or f"f{len(report['translated']) + 1}")
        op = str(f.get("op") or "").lower()
        p = dict(f.get("params") or {})
        if op == "sketch":
            last_sketch = _sketch_block(fid, p, lines, report)
            last_plane = str(p.get("plane") or "XY").upper()
        elif op == "extrude" and last_sketch:
            _extrude_block(fid, p, last_sketch, lines, report)
        elif op == "revolve" and last_sketch:
            _revolve_block(fid, p, last_sketch, last_plane, lines, report)
        elif op == "hole":
            _hole_block(fid, p, last_plane, lines, report)
        elif op == "fillet":
            _fillet_block(fid, p, lines, report)
        elif op == "pattern":
            _pattern_block(fid, p, lines, report)
        else:
            reason = ("a sketch must exist before a solid feature" if op in ("extrude", "revolve")
                      else f"no SolidWorks mapping for op '{op}'")
            report["skipped"].append({"feature": fid, "op": op, "reason": reason})
            lines.append(f"    ' [{fid}] NOT TRANSLATED ({op}): {reason}")
    if report["skipped"]:
        lines.append("    ' --- features that were NOT translated (see the export report) ---")
        for s in report["skipped"]:
            lines.append(f"    '   {s['feature']} ({s['op']}): {s['reason']}")
    if report["manual"]:
        lines.append("    ' --- translated, but one selection must be made by hand ---")
        for s in report["manual"]:
            lines.append(f"    '   {s['feature']}: {s['what']}")
    _footer(lines)
    report["vba"] = "\n".join(lines) + "\n"
    report["notes"] = [
        "Generated from the documented SolidWorks API; NOT executed in SolidWorks here (there is no SolidWorks "
        "in this sandbox). Someone with SolidWorks has to run it once and check the rebuild.",
        "Lengths are metres (API unit); each line's comment repeats the millimetre value IDRIS used.",
        "A hole becomes a circular cut, not a Hole Wizard hole; a fillet on 'all' edges needs the edges selected.",
    ]
    return report


ALLOWED_STATEMENT = re.compile(r"^(Set |Dim |boolstatus|swModel|swSketchMgr|swFeatureMgr|swApp|If |Else|End |"
                              r"Next|Option |Sub |Function |MsgBox |Exit Sub|On Error|'|$|swDim\.)")


def check_vba(text: str) -> tuple:
    """A syntax-level check that can run without SolidWorks: blocks balance and every line is a VBA statement."""
    opens = {"Sub": 0, "If": 0, "For": 0}
    problems = []
    for i, raw in enumerate(text.splitlines(), 1):
        line = raw.strip()
        if not line:
            continue
        if not ALLOWED_STATEMENT.match(line):
            problems.append(f"line {i}: not a VBA statement: {line[:60]}")
        low = line.lower()
        if low.startswith("sub ") and not low.startswith("sub main"):
            opens["Sub"] += 1
        elif low.startswith("sub main"):
            opens["Sub"] += 1
        elif low == "end sub":
            opens["Sub"] -= 1
        elif low.startswith("if ") and not low.endswith("then") is False and "then" in low:
            opens["If"] += 1
        elif low == "end if":
            opens["If"] -= 1
        elif low.startswith("for "):
            opens["For"] += 1
        elif low == "next":
            opens["For"] -= 1
    for k, v in opens.items():
        if v != 0:
            problems.append(f"unbalanced {k} block (balance {v})")
    if "Application.SldWorks" not in text:
        problems.append("the macro never touches Application.SldWorks")
    return (not problems), problems
