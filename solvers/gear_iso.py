"""ISO 6336-3 tooth-form factors as an ACE solver (benchmark for the "iso6336" reference)."""
from ace_core import SolverSpec, Benchmark, register
from physics.toothform import tooth_form, iso_closed_form


def _run(p):
    z = int(p["teeth"])
    t = tooth_form(z)
    return {"outputs": {"YF": round(t["YF"], 4), "YS": round(t["YS"], 4), "YFS": round(t["YF"] * t["YS"], 4),
                        "sFn_over_m": round(t["sFn"], 4), "hFe_over_m": round(t["hFe"], 4),
                        "rhoF_over_m": round(t["rhoF"], 4)}}


_ref = {z: iso_closed_form(z) for z in (17, 20, 50, 100)}

register(SolverSpec(
    name="gear_tooth_form_iso", version="0.2.0", domain="machine_elements", fidelity="L0",
    summary="Tooth form factor Y_F and stress correction factor Y_S of a spur gear (load at the tooth tip), "
            "from the trochoid root generated by the ISO 53 basic rack (x = 0).",
    method="Numerical trochoid of the rack tip (ρfP = 0.38 m, hfP = 1.25 m, α = 20°), 30° tangent critical section, "
           "ISO 6336-3 Y_F and Y_S formulas",
    schema={"teeth": {"type": "integer", "min": 12, "max": 400, "required": True}},
    run=_run,
    benchmarks=[Benchmark(f"iso6336-3-closed-form-z{z}",
                          f"ISO 6336-3:2006 §6 closed-form equations (independent implementation), z = {z}, x = 0; "
                          "consistent with the standard's Y_Fa/Y_Sa charts (e.g. z = 20: Y_Fa ≈ 2.80, Y_Sa ≈ 1.55)",
                          {"teeth": z}, {"outputs.YF": round(_ref[z]["YF"], 4), "outputs.YS": round(_ref[z]["YS"], 4)},
                          0.02) for z in _ref],
    limitations=["profile shift x = 0 only", "no protuberance / grinding notch", "spur gears (β = 0)"],
    example={"teeth": 20},
))
